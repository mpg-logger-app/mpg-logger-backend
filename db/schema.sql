-- Creates the mpglogger schema and its tables in the mpgloggerdb database. Safe to run more than once.
-- This is the full schema for a NEW database. A database created before accounts existed
-- is upgraded with the scripts in db/migrations/ instead (see README).
-- Columns match the JPA entities (Hibernate validates them on startup).
-- "date" and "user" are avoided as names because they are SQL keywords.
-- float8 is PostgreSQL's DOUBLE PRECISION (a Java double), written as one word.
-- The CHECKs repeat rules from FuelLogRules / AccountRules, so bad rows can't get in even outside the API.
-- No blank lines inside a statement: DBeaver treats a blank line as the end of a statement.

CREATE SCHEMA IF NOT EXISTS mpglogger;

-- Usernames are stored lowercase, so the UNIQUE constraint makes them unique regardless of case.
-- password_hash is a BCrypt hash; the password itself is never stored.
CREATE TABLE IF NOT EXISTS mpglogger.app_user (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(30)  NOT NULL,
    name          varchar(50)  NOT NULL,
    password_hash varchar(100) NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT app_user_username_unique    UNIQUE (username),
    CONSTRAINT app_user_username_lowercase CHECK (username = lower(username)),
    CONSTRAINT app_user_username_length    CHECK (char_length(username) >= 3),
    CONSTRAINT app_user_name_not_blank     CHECK (btrim(name) <> '')
);

-- One row per signed-in browser. token_hash is the SHA-256 of the cookie value, never the value itself.
-- Deleting a user signs them out everywhere.
CREATE TABLE IF NOT EXISTS mpglogger.user_session (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES mpglogger.app_user (id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT user_session_token_hash_unique UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS user_session_user_idx ON mpglogger.user_session (user_id);

-- Each log belongs to one user. Deleting a user deletes their logs.
CREATE TABLE IF NOT EXISTS mpglogger.fuel_log (
    id                bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint  NOT NULL REFERENCES mpglogger.app_user (id) ON DELETE CASCADE,
    fuel_date         date    NOT NULL,
    previous_odometer float8  NOT NULL,
    odometer          float8  NOT NULL,
    gallons           float8  NOT NULL,
    price_per_gallon  float8  NOT NULL,
    CONSTRAINT fuel_log_previous_odometer_positive CHECK (previous_odometer > 0),
    CONSTRAINT fuel_log_odometer_increases         CHECK (odometer > previous_odometer),
    CONSTRAINT fuel_log_gallons_positive           CHECK (gallons > 0),
    CONSTRAINT fuel_log_price_positive             CHECK (price_per_gallon > 0)
);

-- The API always looks up one user's logs by highest odometer.
CREATE INDEX IF NOT EXISTS fuel_log_user_odometer_idx ON mpglogger.fuel_log (user_id, odometer DESC);
