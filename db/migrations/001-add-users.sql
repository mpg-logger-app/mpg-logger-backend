-- Upgrade, step 1 of 2: adds users and sessions to a database created before accounts existed.
-- Safe to run more than once. Run this BEFORE deploying the backend that has sign-in.
--
-- Existing fuel logs get an empty user_id for now, so nobody sees them. After you sign up,
-- 002-claim-existing-logs.sql gives them to your account and makes user_id required.
-- No blank lines inside a statement: DBeaver treats a blank line as the end of a statement.

CREATE TABLE IF NOT EXISTS mpglogger.app_user (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(30)  NOT NULL,
    name          varchar(50)  NOT NULL,
    password_hash varchar(100) NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT app_user_username_unique    UNIQUE (username),
    CONSTRAINT app_user_username_lowercase CHECK (username = lower(username)),
    CONSTRAINT app_user_username_length    CHECK (char_length(username) >= 3),
    CONSTRAINT app_user_name_not_blank     CHECK (btrim(name) <> '')
);

CREATE TABLE IF NOT EXISTS mpglogger.user_session (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES mpglogger.app_user (id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT user_session_token_hash_unique UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS user_session_user_idx ON mpglogger.user_session (user_id);

ALTER TABLE mpglogger.fuel_log
    ADD COLUMN IF NOT EXISTS user_id bigint REFERENCES mpglogger.app_user (id) ON DELETE CASCADE;

-- Lookups are now per user; the old index only covered odometer.
CREATE INDEX IF NOT EXISTS fuel_log_user_odometer_idx ON mpglogger.fuel_log (user_id, odometer DESC);

DROP INDEX IF EXISTS mpglogger.fuel_log_odometer_idx;
