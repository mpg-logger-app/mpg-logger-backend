-- Creates the mpglogger schema and its tables in the mpgloggerdb database. Safe to run more than once.
-- Columns match the FuelLog JPA entity (Hibernate validates them on startup).
-- "date" is avoided as a column name because it is an SQL keyword.
-- float8 is PostgreSQL's DOUBLE PRECISION (a Java double), written as one word.
-- The CHECKs are the same rules as FuelLogRules, so bad rows can't get in even outside the API.
-- No blank lines inside a statement: DBeaver treats a blank line as the end of a statement.

CREATE SCHEMA IF NOT EXISTS mpglogger;

CREATE TABLE IF NOT EXISTS mpglogger.fuel_log (
    id                bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuel_date         date    NOT NULL,
    previous_odometer float8  NOT NULL,
    odometer          float8  NOT NULL,
    gallons           float8  NOT NULL,
    price_per_gallon  float8  NOT NULL,
    CONSTRAINT fuel_log_previous_odometer_positive CHECK (previous_odometer > 0),
    CONSTRAINT fuel_log_odometer_increases         CHECK (odometer > previous_odometer),
    CONSTRAINT fuel_log_gallons_positive           CHECK (gallons > 0),
    CONSTRAINT fuel_log_price_positive             CHECK (price_per_gallon > 0)
);

-- The API always sorts and looks up by highest odometer.
CREATE INDEX IF NOT EXISTS fuel_log_odometer_idx ON mpglogger.fuel_log (odometer DESC);
